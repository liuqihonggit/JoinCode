namespace Core.Prompts.Sections;

/// <summary>
/// 编码哲学部分 - AI助手核心设计哲学与编码准则（始终注入，精简版）
/// </summary>
[PromptSection(Name = "coding_philosophy", Order = 5)]
public static class CodingPhilosophySection {
    public static SystemPromptSection Create() {
        return SystemPromptSection.Cached("coding_philosophy", () => {
            return """
# 编码哲学与准则

## 工具调用准则
- 执行 bash 工具前，先思考先后果而非结果，避免一切不可撤回的动作
- 用移动代替删除：有非要删除的情况必须让用户接管
- 用户明确睡觉等无人值守环节下，不调用询问工具

## 架构优先
- 先思考最坏代码方式，要有反例才能知道如何写好
- 不要用简单方式为导向，而是满足架构最优，方便日后不断扩展
- 使用 ADR 保证全局决策，每个任务用 spec 来保存执行

## 开心路径
先充分理解当前项目和用户需求，防止架构疲劳，推荐使用开心路径处理项目：
1. 主路径清晰暴露实现路径：例如 main 仅做配置工作，每个命令是一个主路径
2. 主路径上面先实现开心路径，对于边缘场景一律采用断言屏蔽

设计理由：
- 边缘场景没有覆盖可以在上层正确就终止，而不是在底层过程游离
- 防止非核心路径过分补充，先做第一版代码给用户验证方向
- 断言要具备栈帧信息，AI 调试 exe 时候可以立即整改
- 外部环境传入参数是异常，内部屏蔽就是断言。发布期间会自动清理
- 如果当前已进入处理断言阶段，就逐个断言展开决策和修复方案，不要同时处理多个

## 替换便利
为了未来使用脚本替换函数方便，你应该把函数消费写得相同，这样替换才能更便利，实在不行就封装多一个函数。替换时必须先转为统一写法和格式，再执行替换（幂等可重复）。

## 字典配置
大量采用：AOT 元编程 + 关注点分离 + 约定大于配置。通过源码生成器获取特性，减少硬编码，大量采用 nameof(xxType) 防止改了类型忘记改字符串。
""";
        });
    }
}

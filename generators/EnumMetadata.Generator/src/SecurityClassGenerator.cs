using System;

namespace EnumMetadata.Generator;

/// <summary>
/// 工具安全分类源码生成器 — 扫描 [SecurityClass] 特性，自动生成工具安全集合
/// 产出 ToolSecuritySets 静态类，包含 ReadOnlyTools / SafeWriteTools / SensitiveTools / AgentDestructiveTools
/// 以及 AutoAllowedTools / PlanAllowedTools / AskAllowedTools / AutoDeniedTools / PlanDeniedTools / AskDeniedTools
/// </summary>
[Generator]
public sealed class SecurityClassGenerator : IIncrementalGenerator
{
    private const string SecurityClassAttributeFullName = "JoinCode.Abstractions.Attributes.SecurityClassAttribute";
    private const string EnumValueAttributeFullName = "JoinCode.Abstractions.Attributes.EnumValueAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var toolInfos = context.CompilationProvider
            .SelectMany(static (compilation, _) =>
            {
                var securityAttr = compilation.GetTypeByMetadataName(SecurityClassAttributeFullName);
                var enumValueAttr = compilation.GetTypeByMetadataName(EnumValueAttributeFullName);
                if (securityAttr is null || enumValueAttr is null)
                    return ImmutableArray<ToolSecurityInfo>.Empty;

                var results = new List<ToolSecurityInfo>();
                VisitNamespaces(compilation.GlobalNamespace, compilation.Assembly, securityAttr, enumValueAttr, results);
                return results.ToImmutableArray();
            })
            .Collect();

        context.RegisterSourceOutput(toolInfos, static (ctx, tools) =>
        {
            GenerateToolSecuritySets(ctx, tools);
        });
    }

    private static void VisitNamespaces(
        INamespaceSymbol namespaceSymbol,
        IAssemblySymbol currentAssembly,
        INamedTypeSymbol securityAttr,
        INamedTypeSymbol enumValueAttr,
        List<ToolSecurityInfo> results)
    {
        foreach (var member in namespaceSymbol.GetMembers())
        {
            if (member is INamespaceSymbol childNamespace)
                VisitNamespaces(childNamespace, currentAssembly, securityAttr, enumValueAttr, results);
            else if (member is INamedTypeSymbol { TypeKind: TypeKind.Enum } enumType
                     && SymbolEqualityComparer.Default.Equals(enumType.ContainingAssembly, currentAssembly))
            {
                foreach (var field in enumType.GetMembers().OfType<IFieldSymbol>())
                {
                    var secAttr = field.GetAttributes()
                        .FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, securityAttr));

                    if (secAttr is null) continue;

                    var valAttr = field.GetAttributes()
                        .FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, enumValueAttr));

                    var toolName = valAttr?.ConstructorArguments.ElementAtOrDefault(0).Value as string ?? field.Name;

                    var classification = secAttr.ConstructorArguments.ElementAtOrDefault(0).Value as string ?? "unknown";

                    var namedArgs = secAttr.NamedArguments;

                    bool GetNamedArg(string name, bool defaultVal = false)
                    {
                        foreach (var kvp in namedArgs)
                        {
                            if (kvp.Key == name && kvp.Value.Value is bool v)
                                return v;
                        }
                        return defaultVal;
                    }

                    results.Add(new ToolSecurityInfo(
                        ToolName: toolName,
                        Classification: classification,
                        AutoAllowed: GetNamedArg("AutoAllowed"),
                        PlanAllowed: GetNamedArg("PlanAllowed"),
                        AskAllowed: GetNamedArg("AskAllowed"),
                        AutoDenied: GetNamedArg("AutoDenied"),
                        PlanDenied: GetNamedArg("PlanDenied"),
                        AskDenied: GetNamedArg("AskDenied"),
                        AgentDestructive: GetNamedArg("AgentDestructive")));
                }
            }
        }
    }

    private static void GenerateToolSecuritySets(SourceProductionContext context, ImmutableArray<ToolSecurityInfo> tools)
    {
        if (tools.IsEmpty) return;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine();
        sb.AppendLine("namespace JoinCode.Abstractions.Security;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// 工具安全分类集合 — 由 SecurityClassGenerator 从 [SecurityClass] 特性自动生成");
        sb.AppendLine("/// 数据源: 各工具枚举上的 [SecurityClass] 特性标记");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class ToolSecuritySets");
        sb.AppendLine("{");

        GenerateClassificationSet(sb, "ReadOnlyTools", tools, "readonly");
        GenerateClassificationSet(sb, "SafeWriteTools", tools, "safe-write");
        GenerateClassificationSet(sb, "SensitiveTools", tools, "sensitive");

        GeneratePermissionSet(sb, "AutoAllowedTools", tools, t => t.AutoAllowed);
        GeneratePermissionSet(sb, "PlanAllowedTools", tools, t => t.PlanAllowed);
        GeneratePermissionSet(sb, "AskAllowedTools", tools, t => t.AskAllowed);
        GeneratePermissionSet(sb, "AutoDeniedTools", tools, t => t.AutoDenied);
        GeneratePermissionSet(sb, "PlanDeniedTools", tools, t => t.PlanDenied);
        GeneratePermissionSet(sb, "AskDeniedTools", tools, t => t.AskDenied);
        GeneratePermissionSet(sb, "AgentDestructiveTools", tools, t => t.AgentDestructive);

        sb.AppendLine("}");

        context.AddSource("ToolSecuritySets.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateClassificationSet(StringBuilder sb, string setName, ImmutableArray<ToolSecurityInfo> tools, string classification)
    {
        var matching = tools.Where(t => t.Classification == classification).ToList();
        if (matching.Count == 0)
        {
            sb.AppendLine($"    public static readonly FrozenSet<string> {setName} = FrozenSet<string>.Empty;");
            sb.AppendLine();
            return;
        }

        sb.AppendLine($"    public static readonly FrozenSet<string> {setName} = new HashSet<string>(StringComparer.OrdinalIgnoreCase)");
        sb.AppendLine("    {");
        for (int i = 0; i < matching.Count; i++)
        {
            var comma = i < matching.Count - 1 ? "," : ",";
            sb.AppendLine($"        \"{EscapeString(matching[i].ToolName)}\"{comma}");
        }
        sb.AppendLine("    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);");
        sb.AppendLine();
    }

    private static void GeneratePermissionSet(StringBuilder sb, string setName, ImmutableArray<ToolSecurityInfo> tools, Func<ToolSecurityInfo, bool> predicate)
    {
        var matching = tools.Where(predicate).ToList();
        if (matching.Count == 0)
        {
            sb.AppendLine($"    public static readonly FrozenSet<string> {setName} = FrozenSet<string>.Empty;");
            sb.AppendLine();
            return;
        }

        sb.AppendLine($"    public static readonly FrozenSet<string> {setName} = new HashSet<string>(StringComparer.OrdinalIgnoreCase)");
        sb.AppendLine("    {");
        for (int i = 0; i < matching.Count; i++)
        {
            sb.AppendLine($"        \"{EscapeString(matching[i].ToolName)}\",");
        }
        sb.AppendLine("    }.ToFrozenSet(StringComparer.OrdinalIgnoreCase);");
        sb.AppendLine();
    }

    private static string EscapeString(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private sealed class ToolSecurityInfo
    {
        public string ToolName { get; }
        public string Classification { get; }
        public bool AutoAllowed { get; }
        public bool PlanAllowed { get; }
        public bool AskAllowed { get; }
        public bool AutoDenied { get; }
        public bool PlanDenied { get; }
        public bool AskDenied { get; }
        public bool AgentDestructive { get; }

        public ToolSecurityInfo(string ToolName, string Classification, bool AutoAllowed, bool PlanAllowed, bool AskAllowed, bool AutoDenied, bool PlanDenied, bool AskDenied, bool AgentDestructive)
        {
            this.ToolName = ToolName;
            this.Classification = Classification;
            this.AutoAllowed = AutoAllowed;
            this.PlanAllowed = PlanAllowed;
            this.AskAllowed = AskAllowed;
            this.AutoDenied = AutoDenied;
            this.PlanDenied = PlanDenied;
            this.AskDenied = AskDenied;
            this.AgentDestructive = AgentDestructive;
        }
    }
}

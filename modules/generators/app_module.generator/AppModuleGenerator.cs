using System;
using System.IO;
using System.Linq;

namespace AppModule.Generator;

/// <summary>
/// AppModule 源码生成器 — 扫描 [AppModule] 只负责「发现模块」，
/// 启动顺序与会话分组由 resources/app/modules.yaml 的 profiles 显式声明。
/// </summary>
[Generator]
public sealed class AppModuleGenerator : IIncrementalGenerator {
    private const string AppModuleAttributeFullName = "JoinCode.App.Builder.AppModuleAttribute";

    /// <summary>YAML 与特性之间不一致 — 显式设计不允许静默漏掉或多出一个模块。</summary>
    private static readonly DiagnosticDescriptor ModuleMismatch = new(
        "JCCGEN002",
        "模块注册名不一致",
        "模块 '{0}' 在 modules.yaml 与 [AppModule] 特性之间不一致（{1}）",
        "Generator",
        DiagnosticSeverity.Error,
        isEnabledByDefault: true);

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var moduleTypes = context.CompilationProvider
            .SelectMany(static (compilation, _) => {
                var appModuleAttr = compilation.GetTypeByMetadataName(AppModuleAttributeFullName);
                if (appModuleAttr is null)
                    return ImmutableArray<TypeInfo>.Empty;

                var results = new List<TypeInfo>();
                VisitNamespaces(compilation.GlobalNamespace, appModuleAttr, results);
                return results.ToImmutableArray();
            })
            .Collect();

        var orderFiles = context.AdditionalTextsProvider
            .Where(static file => string.Equals(Path.GetFileName(file.Path), "modules.yaml", StringComparison.OrdinalIgnoreCase))
            .Collect();

        context.RegisterSourceOutput(moduleTypes.Combine(orderFiles), static (ctx, pair) => {
            var orderSource = pair.Right.Length > 0 ? pair.Right[0].GetText() : null;
            var orderText = orderSource is null ? "" : orderSource.ToString();
            var profiles = OrderYaml.ParseProfiles(orderText);
            if (profiles.Count == 0) {
                ctx.ReportDiagnostic(Diagnostic.Create(ModuleMismatch, Location.None, "modules.yaml", "没有定义任何 profile"));
                return;
            }

            var byName = pair.Left.ToDictionary(
                module => ShortName(module.FullyQualifiedName),
                module => module,
                StringComparer.OrdinalIgnoreCase);

            foreach (var entry in profiles) {
                foreach (var name in entry.Value) {
                    if (!byName.ContainsKey(name))
                        ctx.ReportDiagnostic(Diagnostic.Create(ModuleMismatch, Location.None, name,
                            $"profile '{entry.Key}' 声明了它，但没有 [AppModule] 类型"));
                }
            }
            foreach (var name in byName.Keys) {
                if (!profiles.Values.Any(names => names.Contains(name, StringComparer.OrdinalIgnoreCase)))
                    ctx.ReportDiagnostic(Diagnostic.Create(ModuleMismatch, Location.None, name,
                        "有 [AppModule] 类型，但没有任何 profile 声明它"));
            }

            GenerateModuleCatalog(ctx, profiles, byName);
        });
    }

    private static string ShortName(string fullyQualifiedName) =>
        fullyQualifiedName.Split('.').Last().TrimEnd('>');

    private static void VisitNamespaces(
        INamespaceSymbol namespaceSymbol,
        INamedTypeSymbol targetAttr,
        List<TypeInfo> results) {
        foreach (var member in namespaceSymbol.GetMembers()) {
            if (member is INamespaceSymbol childNamespace)
                VisitNamespaces(childNamespace, targetAttr, results);
            else if (member is INamedTypeSymbol typeSymbol) {
                var attr = typeSymbol.GetAttributes()
                    .FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, targetAttr));

                if (attr is not null)
                    results.Add(new TypeInfo(typeSymbol.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)));
            }
        }
    }

    private static void GenerateModuleCatalog(
        SourceProductionContext context,
        IReadOnlyDictionary<string, IReadOnlyList<string>> profiles,
        IReadOnlyDictionary<string, TypeInfo> byName) {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using JoinCode.App.Builder;");
        sb.AppendLine();
        sb.AppendLine("namespace JoinCode.App.Builder;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// 会话模块目录 — 由 AppModule.Generator 从 resources/app/modules.yaml 生成。");
        sb.AppendLine("/// 顺序与分组都是显式设计，不再扫描特性上的排序数字。");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class AppModuleCatalog");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>按 profile 取模块实例（顺序即 YAML 声明顺序）。</summary>");
        sb.AppendLine("    public static IEnumerable<IAppModule> Create(string profile) => profile switch {");

        foreach (var entry in profiles) {
            var modules = entry.Value
                .Where(byName.ContainsKey)
                .Select(name => $"new {byName[name].FullyQualifiedName}()");
            sb.AppendLine($"        \"{entry.Key}\" => new IAppModule[] {{ {string.Join(", ", modules)} }},");
        }

        sb.AppendLine("        _ => throw new ArgumentException($\"未知模块 profile '{profile}'（AppModuleCatalog 查找层拦截）。现有: "
            + string.Join(", ", profiles.Keys) + "\", nameof(profile))");
        sb.AppendLine("    };");
        sb.AppendLine("}");

        context.AddSource("GeneratedAppModuleCatalog.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private sealed class TypeInfo {
        public string FullyQualifiedName { get; }

        public TypeInfo(string fullyQualifiedName) {
            FullyQualifiedName = fullyQualifiedName;
        }
    }
}

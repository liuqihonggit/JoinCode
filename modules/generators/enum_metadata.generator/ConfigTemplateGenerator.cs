
namespace SettingsMerge.Generator;

/// <summary>
/// 配置模板源码生成器 — 扫描 [SettingsMerge] 类的 [JsonPropertyName] 属性，编译时生成 JSON 模板字符串。
/// <para>
/// ADR 0114: 改 C# 类属性 → 重新编译 → JSON 模板自动更新，单一数据源。
/// 生成 ConfigTemplates 静态类，含每个 [SettingsMerge] 类的 GetXxxTemplate() 方法。
/// </para>
/// </summary>
[Generator]
public sealed class ConfigTemplateGenerator : IIncrementalGenerator {
    private const string SettingsMergeAttributeFullName = "JoinCode.Abstractions.Attributes.SettingsMergeAttribute";
    private const string JsonPropertyNameAttributeFullName = "System.Text.Json.Serialization.JsonPropertyNameAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var classInfos = context.CompilationProvider
            .SelectMany(static (compilation, _) => {
                var mergeAttr = compilation.GetTypeByMetadataName(SettingsMergeAttributeFullName);
                var jsonPropAttr = compilation.GetTypeByMetadataName(JsonPropertyNameAttributeFullName);
                if (mergeAttr is null || jsonPropAttr is null)
                    return ImmutableArray<TemplateClassInfo>.Empty;

                var results = new List<TemplateClassInfo>();
                var allMergeClasses = new Dictionary<string, TemplateClassInfo>(StringComparer.Ordinal);

                CollectMergeClasses(compilation.GlobalNamespace, compilation.Assembly, mergeAttr, jsonPropAttr, allMergeClasses);

                foreach (var info in allMergeClasses.Values) {
                    info.NestedClasses = allMergeClasses.ToImmutableDictionary();
                    results.Add(info);
                }

                return results.ToImmutableArray();
            })
            .Collect();

        context.RegisterSourceOutput(classInfos, static (ctx, classes) => {
            if (classes.IsEmpty) return;
            GenerateConfigTemplates(ctx, classes);
        });
    }

    private static void CollectMergeClasses(
        INamespaceSymbol namespaceSymbol,
        IAssemblySymbol currentAssembly,
        INamedTypeSymbol mergeAttr,
        INamedTypeSymbol? jsonPropAttr,
        Dictionary<string, TemplateClassInfo> results) {
        foreach (var member in namespaceSymbol.GetMembers()) {
            if (member is INamespaceSymbol childNamespace)
                CollectMergeClasses(childNamespace, currentAssembly, mergeAttr, jsonPropAttr, results);
            else if (member is INamedTypeSymbol { TypeKind: TypeKind.Class } classType
                     && SymbolEqualityComparer.Default.Equals(classType.ContainingAssembly, currentAssembly)) {
                var hasMergeAttr = classType.GetAttributes()
                    .Any(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, mergeAttr));
                if (!hasMergeAttr) continue;

                var properties = new List<TemplatePropertyInfo>();
                foreach (var prop in classType.GetMembers().OfType<IPropertySymbol>()) {
                    if (prop.DeclaredAccessibility != Accessibility.Public) continue;
                    if (prop.SetMethod is null) continue;

                    var jsonName = prop.GetAttributes()
                        .FirstOrDefault(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, jsonPropAttr))
                        ?.ConstructorArguments.ElementAtOrDefault(0).Value as string;

                    if (jsonName is null) continue;

                    properties.Add(new TemplatePropertyInfo(
                        prop.Name,
                        jsonName,
                        prop.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat),
                        prop.Type.OriginalDefinition.ToDisplayString(),
                        prop.Type.IsReferenceType,
                        prop.Type.NullableAnnotation == NullableAnnotation.Annotated));
                }

                var key = classType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
                results[key] = new TemplateClassInfo(
                    key,
                    classType.Name,
                    classType.ContainingNamespace.ToDisplayString(),
                    properties.ToImmutableArray(),
                    ImmutableDictionary<string, TemplateClassInfo>.Empty);
            }
        }
    }

    private static void GenerateConfigTemplates(SourceProductionContext context, ImmutableArray<TemplateClassInfo> classes) {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("namespace Core.Configuration.Templates;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// 配置模板 — 源码生成器自动生成，改 C# 类属性后重新编译自动更新（ADR 0114）");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class ConfigTemplates");
        sb.AppendLine("{");

        var first = true;
        foreach (var classInfo in classes) {
            if (!first) sb.AppendLine();
            first = false;
            GenerateTemplateMethod(sb, classInfo, classes);
        }

        sb.AppendLine("}");

        context.AddSource("ConfigTemplates.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateTemplateMethod(StringBuilder sb, TemplateClassInfo classInfo, ImmutableArray<TemplateClassInfo> allClasses) {
        var methodName = $"Get{classInfo.Name}Template";

        sb.AppendLine("    /// <summary>");
        sb.AppendLine($"    /// {classInfo.Name} 的 JSON 模板 — 自动生成，默认值基于属性类型");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine($"    public static string {methodName}() => \"\"\"");
        sb.AppendLine();
        GenerateJsonBody(sb, classInfo, allClasses, indent: "  ");
        sb.AppendLine();
        sb.AppendLine("\"\"\";");
    }

    private static void GenerateJsonBody(StringBuilder sb, TemplateClassInfo classInfo, ImmutableArray<TemplateClassInfo> allClasses, string indent) {
        sb.AppendLine("{");
        var props = classInfo.Properties;
        for (var i = 0; i < props.Length; i++) {
            var prop = props[i];
            var comma = i < props.Length - 1 ? "," : "";
            var defaultValue = GetDefaultValue(prop, allClasses, indent + "  ");
            sb.AppendLine($"{indent}  \"{prop.JsonName}\": {defaultValue}{comma}");
        }
        sb.Append($"{indent}}}");
    }

    private static string GetDefaultValue(TemplatePropertyInfo prop, ImmutableArray<TemplateClassInfo> allClasses, string indent) {
        var typeDef = prop.TypeDefinition;

        if (typeDef.Contains("Dictionary<"))
            return "{}";
        if (typeDef.Contains("List<") || typeDef.Contains("IReadOnlyList<"))
            return "[]";

        foreach (var cls in allClasses) {
            if (prop.FullyQualifiedType.StartsWith(cls.FullyQualifiedName)) {
                var nestedSb = new StringBuilder();
                GenerateJsonBody(nestedSb, cls, allClasses, indent);
                return nestedSb.ToString();
            }
        }

        if (prop.IsNullable)
            return "null";

        if (typeDef == "string") return "\"\"";
        if (typeDef == "bool") return "false";
        if (typeDef == "int" || typeDef == "long") return "0";
        if (typeDef == "double" || typeDef == "float") return "0.0";

        return "null";
    }

    private sealed class TemplateClassInfo {
        public string FullyQualifiedName { get; set; } = "";
        public string Name { get; set; } = "";
        public string Namespace { get; set; } = "";
        public ImmutableArray<TemplatePropertyInfo> Properties { get; set; }
        public ImmutableDictionary<string, TemplateClassInfo> NestedClasses { get; set; } = ImmutableDictionary<string, TemplateClassInfo>.Empty;

        public TemplateClassInfo() { }
        public TemplateClassInfo(string fullyQualifiedName, string name, string ns, ImmutableArray<TemplatePropertyInfo> properties, ImmutableDictionary<string, TemplateClassInfo> nestedClasses) {
            FullyQualifiedName = fullyQualifiedName;
            Name = name;
            Namespace = ns;
            Properties = properties;
            NestedClasses = nestedClasses;
        }
    }

    private sealed class TemplatePropertyInfo {
        public string Name { get; set; } = "";
        public string JsonName { get; set; } = "";
        public string FullyQualifiedType { get; set; } = "";
        public string TypeDefinition { get; set; } = "";
        public bool IsReferenceType { get; set; }
        public bool IsNullable { get; set; }

        public TemplatePropertyInfo() { }
        public TemplatePropertyInfo(string name, string jsonName, string fullyQualifiedType, string typeDefinition, bool isReferenceType, bool isNullable) {
            Name = name;
            JsonName = jsonName;
            FullyQualifiedType = fullyQualifiedType;
            TypeDefinition = typeDefinition;
            IsReferenceType = isReferenceType;
            IsNullable = isNullable;
        }
    }
}
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;

namespace ParamMetadata.Generator;

/// <summary>
/// 参数元数据源码生成器 — 扫描 WellKnownParam 枚举的 [EnumValue] + [ParamMeta] 特性，
/// 生成 WellKnownParamDescriptions（描述常量）+ WellKnownParamMeta（元数据字典）。
/// </summary>
[Generator]
public sealed class ParamMetadataGenerator : IIncrementalGenerator {
    private const string WellKnownParamEnumFullName = "JoinCode.Abstractions.Utils.WellKnownParam";
    private const string EnumValueAttrFullName = "JoinCode.Abstractions.Attributes.EnumValueAttribute";
    private const string ParamMetaAttrFullName = "JoinCode.Abstractions.Attributes.ParamMetaAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context) {
        var paramInfos = context.CompilationProvider
            .SelectMany(static (compilation, _) => {
                var enumType = compilation.GetTypeByMetadataName(WellKnownParamEnumFullName);
                if (enumType is null || enumType.TypeKind != TypeKind.Enum)
                    return ImmutableArray<ParamInfo>.Empty;

                var enumValueAttr = compilation.GetTypeByMetadataName(EnumValueAttrFullName);
                var paramMetaAttr = compilation.GetTypeByMetadataName(ParamMetaAttrFullName);
                if (enumValueAttr is null || paramMetaAttr is null)
                    return ImmutableArray<ParamInfo>.Empty;

                var results = new List<ParamInfo>();
                foreach (var member in enumType.GetMembers()) {
                    if (member is not IFieldSymbol field || field.HasConstantValue == false)
                        continue;

                    var enumValue = GetFirstEnumValue(field, enumValueAttr);
                    var meta = GetParamMeta(field, paramMetaAttr);
                    if (enumValue is null || meta is null)
                        continue;

                    results.Add(new ParamInfo(
                        field.Name,
                        enumValue,
                        meta.Value.Description,
                        meta.Value.Required,
                        meta.Value.DefaultValue,
                        meta.Value.TypeName));
                }

                return results.ToImmutableArray();
            })
            .Collect();

        context.RegisterSourceOutput(paramInfos, static (ctx, infos) => {
            GenerateDescriptions(ctx, infos);
            GenerateMetaDictionary(ctx, infos);
        });
    }

    private static string? GetFirstEnumValue(IFieldSymbol field, INamedTypeSymbol attrSymbol) {
        foreach (var attr in field.GetAttributes()) {
            if (!SymbolEqualityComparer.Default.Equals(attr.AttributeClass, attrSymbol))
                continue;
            if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string s)
                return s;
        }
        return null;
    }

    private static (string Description, bool Required, string? DefaultValue, string? TypeName)? GetParamMeta(
        IFieldSymbol field, INamedTypeSymbol attrSymbol) {
        foreach (var attr in field.GetAttributes()) {
            if (!SymbolEqualityComparer.Default.Equals(attr.AttributeClass, attrSymbol))
                continue;

            string? description = null;
            if (attr.ConstructorArguments.Length > 0 && attr.ConstructorArguments[0].Value is string d)
                description = d;

            var required = true;
            var defaultValue = (string?)null;
            var typeName = (string?)null;

            foreach (var kvp in attr.NamedArguments) {
                switch (kvp.Key) {
                    case "Required":
                        if (kvp.Value.Value is bool r)
                            required = r;
                        break;
                    case "DefaultValue":
                        defaultValue = kvp.Value.Value as string;
                        break;
                    case "TypeName":
                        typeName = kvp.Value.Value as string;
                        break;
                }
            }

            if (description is not null)
                return (description, required, defaultValue, typeName);
        }
        return null;
    }

    private static void GenerateDescriptions(SourceProductionContext context, ImmutableArray<ParamInfo> infos) {
        if (infos.Length == 0)
            return;

        var sb = new StringBuilder(2048);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JoinCode.Abstractions.Utils;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// WellKnownParam 参数描述常量 — 由 ParamMetadata.Generator 扫描 [ParamMeta] 特性生成");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class WellKnownParamDescriptions");
        sb.AppendLine("{");

        foreach (var info in infos) {
            var escaped = EscapeString(info.Description);
            sb.AppendLine($"    /// <summary>{info.ParamName} 参数的描述文本</summary>");
            sb.AppendLine($"    public const string {info.EnumMemberName} = \"{escaped}\";");
        }

        sb.AppendLine("}");
        context.AddSource("WellKnownParamDescriptions.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateMetaDictionary(SourceProductionContext context, ImmutableArray<ParamInfo> infos) {
        if (infos.Length == 0)
            return;

        var sb = new StringBuilder(4096);
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine();
        sb.AppendLine("namespace JoinCode.Abstractions.Utils;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// WellKnownParam 参数元数据条目 — 描述/必填/默认值/类型名");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public sealed record WellKnownParamMetaEntry(string Description, bool Required, string? DefaultValue, string? TypeName);");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// WellKnownParam 参数元数据注册表 — 由 ParamMetadata.Generator 扫描 [ParamMeta] 特性生成");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class WellKnownParamMeta");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>按参数名查找元数据的只读字典</summary>");
        sb.AppendLine($"    public static readonly FrozenDictionary<string, WellKnownParamMetaEntry> Entries = BuildEntries();");
        sb.AppendLine();
        sb.AppendLine("    private static FrozenDictionary<string, WellKnownParamMetaEntry> BuildEntries()");
        sb.AppendLine("    {");
        sb.AppendLine($"        var dict = new Dictionary<string, WellKnownParamMetaEntry>({infos.Length});");

        foreach (var info in infos) {
            var descEscaped = EscapeString(info.Description);
            var defaultEscaped = info.DefaultValue is null ? "null" : $"\"{EscapeString(info.DefaultValue)}\"";
            var typeEscaped = info.TypeName is null ? "null" : $"\"{EscapeString(info.TypeName)}\"";
            sb.AppendLine($"        dict[\"{EscapeString(info.ParamName)}\"] = new(\"{descEscaped}\", {info.Required.ToString().ToLowerInvariant()}, {defaultEscaped}, {typeEscaped});");
        }

        sb.AppendLine("        return dict.ToFrozenDictionary();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>按参数名获取描述文本，未找到返回 null</summary>");
        sb.AppendLine("    public static string? GetDescription(string paramName)");
        sb.AppendLine("        => Entries.TryGetValue(paramName, out var entry) ? entry.Description : null;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>按参数名获取是否必填，未找到返回 true</summary>");
        sb.AppendLine("    public static bool GetRequired(string paramName)");
        sb.AppendLine("        => Entries.TryGetValue(paramName, out var entry) && entry.Required;");
        sb.AppendLine("}");

        context.AddSource("WellKnownParamMeta.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string EscapeString(string s) {
        var sb = new StringBuilder(s.Length + 8);
        foreach (var c in s) {
            switch (c) {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default: sb.Append(c); break;
            }
        }
        return sb.ToString();
    }

    private sealed class ParamInfo {
        public string EnumMemberName { get; }
        public string ParamName { get; }
        public string Description { get; }
        public bool Required { get; }
        public string? DefaultValue { get; }
        public string? TypeName { get; }

        public ParamInfo(string enumMemberName, string paramName, string description, bool required, string? defaultValue, string? typeName) {
            EnumMemberName = enumMemberName;
            ParamName = paramName;
            Description = description;
            Required = required;
            DefaultValue = defaultValue;
            TypeName = typeName;
        }
    }
}

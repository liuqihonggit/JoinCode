namespace Scenario.Generator;

/// <summary>
/// 情景模式注册表源码生成器 — 扫描 [Scenario] 特性，生成 ScenarioRegistry 静态类。
/// 对齐 AGENTS.md"字典配置"规范：AOT 元编程 + 特性 + 源码生成器，禁止手写注册表。
/// </summary>
[Generator]
internal sealed class ScenarioGenerator : AttributeRegistrationGeneratorBase<ScenarioGenerator.ScenarioEntry> {
    internal override string AttributeFullName => "JoinCode.Abstractions.Attributes.ScenarioAttribute";

    internal override ScenarioEntry? ExtractInfo(INamedTypeSymbol typeSymbol, AttributeData attr, Compilation compilation) {
        var name = attr.ConstructorArguments.ElementAtOrDefault(0).Value as string;
        var description = attr.ConstructorArguments.ElementAtOrDefault(1).Value as string;
        if (string.IsNullOrEmpty(name) || string.IsNullOrEmpty(description))
            return null;

        var tools = AttributeScanner.GetStringArrayNamedArg(attr, "Tools");
        var suggestedFlow = AttributeScanner.GetStringNamedArg(attr, "SuggestedFlow") ?? "";
        var tips = AttributeScanner.GetStringNamedArg(attr, "Tips") ?? "";

        return new ScenarioEntry(name!, description!, tools, suggestedFlow, tips);
    }

    internal override void GenerateRegistration(SourceProductionContext context, ImmutableArray<ScenarioEntry> infos) {
        var ordered = infos.OrderBy(i => i.Name, StringComparer.Ordinal).ToList();

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("namespace JoinCode.Abstractions.Scenarios;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// 情景模式注册表 — 由 ScenarioGenerator 自动生成，扫描 [Scenario] 特性收集。");
        sb.AppendLine("/// 供 jcc -h scenario 渐进式发现情景模式（工具集 + 建议编排流程 + 提示）。");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class ScenarioRegistry");
        sb.AppendLine("{");

        if (ordered.Count == 0) {
            sb.AppendLine("    /// <summary>空注册表 — 当前程序集无 [Scenario] 特性。</summary>");
            sb.AppendLine("    public static readonly global::JoinCode.Abstractions.Scenarios.ScenarioInfo[] Scenarios = System.Array.Empty<global::JoinCode.Abstractions.Scenarios.ScenarioInfo>();");
        } else {
            sb.AppendLine("    /// <summary>");
            sb.AppendLine("    /// 所有已注册的情景模式 — 按名称排序。");
            sb.AppendLine("    /// </summary>");
            sb.AppendLine("    public static readonly global::JoinCode.Abstractions.Scenarios.ScenarioInfo[] Scenarios = new global::JoinCode.Abstractions.Scenarios.ScenarioInfo[] {");
            foreach (var entry in ordered) {
                var toolsArray = entry.Tools.Length == 0
                    ? "System.Array.Empty<string>()"
                    : "new string[] { " + string.Join(", ", entry.Tools.Select(t => "\"" + EscapeString(t) + "\"")) + " }";
                sb.AppendLine($"        new global::JoinCode.Abstractions.Scenarios.ScenarioInfo(\"{EscapeString(entry.Name)}\", \"{EscapeString(entry.Description)}\", {toolsArray}, \"{EscapeString(entry.SuggestedFlow)}\", \"{EscapeString(entry.Tips)}\"),");
            }
            sb.AppendLine("    };");
        }

        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// 按名称查找情景模式 — 找不到返回 null。");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static global::JoinCode.Abstractions.Scenarios.ScenarioInfo? Find(string name)");
        sb.AppendLine("    {");
        sb.AppendLine("        foreach (var s in Scenarios)");
        sb.AppendLine("        {");
        sb.AppendLine("            if (s.Name == name)");
        sb.AppendLine("                return s;");
        sb.AppendLine("        }");
        sb.AppendLine("        return null;");
        sb.AppendLine("    }");
        sb.AppendLine("}");

        context.AddSource("ScenarioRegistry.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static string EscapeString(string s)
        => s.Replace("\\", "\\\\").Replace("\"", "\\\"").Replace("\n", "\\n").Replace("\r", "\\r").Replace("\t", "\\t");

    internal sealed class ScenarioEntry {
        public string Name { get; }
        public string Description { get; }
        public string[] Tools { get; }
        public string SuggestedFlow { get; }
        public string Tips { get; }

        public ScenarioEntry(string name, string description, string[] tools, string suggestedFlow, string tips) {
            Name = name;
            Description = description;
            Tools = tools;
            SuggestedFlow = suggestedFlow;
            Tips = tips;
        }
    }
}

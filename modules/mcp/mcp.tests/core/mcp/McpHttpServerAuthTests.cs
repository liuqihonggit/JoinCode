namespace Mcp.Tests;

/// <summary>
/// McpHttpServer token 鉴权集成测试 — 启动真实 HttpListener + HttpClient（ADR 0138）
/// </summary>
[Trait("Category", "Integration")]
public class McpHttpServerAuthTests {
    private static int GetFreePort() {
        using var listener = new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback, 0);
        listener.Start();
        var port = ((System.Net.IPEndPoint)listener.LocalEndpoint).Port;
        listener.Stop();
        return port;
    }

    private const string InitializeBody =
        """{"jsonrpc":"2.0","id":1,"method":"initialize","params":{"protocolVersion":"2025-11-25","capabilities":{},"clientInfo":{"name":"test","version":"1.0"}}}""";

    private static HttpRequestMessage CreatePost(string url, string token) {
        var request = new HttpRequestMessage(HttpMethod.Post, url) {
            Content = new StringContent(InitializeBody, Encoding.UTF8, "application/json")
        };
        request.Headers.TryAddWithoutValidation("Authorization", $"Bearer {token}");
        return request;
    }

    private static HttpRequestMessage CreatePostWithMcpToken(string url, string token) {
        var request = new HttpRequestMessage(HttpMethod.Post, url) {
            Content = new StringContent(InitializeBody, Encoding.UTF8, "application/json")
        };
        request.Headers.TryAddWithoutValidation("Mcp-Token", token);
        return request;
    }

    [Fact]
    public async Task PostInitialize_WithoutToken_Returns401() {
        var server = new McpServer("test");
        var port = GetFreePort();
        await using var httpServer = new McpHttpServer(server, $"http://localhost:{port}/mcp/");
        using var cts = new CancellationTokenSource();
        _ = Task.Run(() => httpServer.RunAsync(cts.Token));
        try {
            await Task.Delay(300);
            using var client = new HttpClient();
            using var response = await client.PostAsync(
                $"http://localhost:{port}/mcp/",
                new StringContent(InitializeBody, Encoding.UTF8, "application/json"));
            response.StatusCode.Should().Be(HttpStatusCode.Unauthorized);
            response.Headers.WwwAuthenticate.Should().NotBeEmpty("401 必须带 WWW-Authenticate: Bearer 头");
        } finally {
            cts.Cancel();
            httpServer.Stop();
        }
    }

    [Fact]
    public async Task PostInitialize_WithWrongToken_Returns401() {
        var server = new McpServer("test");
        var port = GetFreePort();
        await using var httpServer = new McpHttpServer(server, $"http://localhost:{port}/mcp/");
        using var cts = new CancellationTokenSource();
        _ = Task.Run(() => httpServer.RunAsync(cts.Token));
        try {
            await Task.Delay(300);
            using var client = new HttpClient();
            using var request = CreatePost($"http://localhost:{port}/mcp/", McpAuthToken.Generate());
            using var response = await client.SendAsync(request);
            response.StatusCode.Should().Be(HttpStatusCode.Unauthorized);
        } finally {
            cts.Cancel();
            httpServer.Stop();
        }
    }

    [Fact]
    public async Task PostInitialize_WithBearerToken_Returns200() {
        var server = new McpServer("test");
        var port = GetFreePort();
        await using var httpServer = new McpHttpServer(server, $"http://localhost:{port}/mcp/");
        using var cts = new CancellationTokenSource();
        _ = Task.Run(() => httpServer.RunAsync(cts.Token));
        try {
            await Task.Delay(300);
            using var client = new HttpClient();
            using var request = CreatePost($"http://localhost:{port}/mcp/", httpServer.AuthToken.Value);
            using var response = await client.SendAsync(request);
            response.StatusCode.Should().Be(HttpStatusCode.OK);
        } finally {
            cts.Cancel();
            httpServer.Stop();
        }
    }

    [Fact]
    public async Task PostInitialize_WithMcpTokenHeader_Returns200() {
        var server = new McpServer("test");
        var port = GetFreePort();
        await using var httpServer = new McpHttpServer(server, $"http://localhost:{port}/mcp/");
        using var cts = new CancellationTokenSource();
        _ = Task.Run(() => httpServer.RunAsync(cts.Token));
        try {
            await Task.Delay(300);
            using var client = new HttpClient();
            using var request = CreatePostWithMcpToken($"http://localhost:{port}/mcp/", httpServer.AuthToken.Value);
            using var response = await client.SendAsync(request);
            response.StatusCode.Should().Be(HttpStatusCode.OK);
        } finally {
            cts.Cancel();
            httpServer.Stop();
        }
    }

    [Fact]
    public async Task AutoGeneratedToken_IsSentInStartup_NotRequiredToTypedTest() {
        var server = new McpServer("test");
        await using var httpServer = new McpHttpServer(server, $"http://localhost:{GetFreePort()}/mcp/");
        httpServer.AuthToken.Value.Should().NotBeNullOrEmpty("自动生成 token 必须由 AuthToken 属性暴露给调用方打印");
    }

    [Fact]
    public void Constructor_EmptyToken_Throws() {
        var server = new McpServer("test");
        var act = () => new McpHttpServer(server, "http://localhost:9905/mcp/", authToken: "");
        act.Should().Throw<ArgumentException>();
    }

    [Fact]
    public async Task Constructor_ExplicitToken_UsedAsIs() {
        var server = new McpServer("test");
        const string explicitToken = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";
        await using var httpServer = new McpHttpServer(server, "http://localhost:9905/mcp/", authToken: explicitToken);
        httpServer.AuthToken.Value.Should().Be(explicitToken);
    }
}

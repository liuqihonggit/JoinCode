def main():
    moved = 0
    errors = []
    
    for f in sorted(ADR_DIR.glob("*.md")):
        m = re.match(r'(\d{4})', f.name)
        if not m:
            continue
        num = m.group(1)
        
        if num not in ADR_TO_TOPIC:
            errors.append(f"未分类 ADR: {num} ({f.name})")
            continue
        
        topic = ADR_TO_TOPIC[num]
        subdir = TOPIC_TO_DIR[topic]
        dst_dir = ADR_DIR / subdir
        dst_dir.mkdir(parents=True, exist_ok=True)
        dst = dst_dir / f.name
        
        if dst.exists():
            errors.append(f"目标已存在: {dst}")
            continue
        
        shutil.move(str(f), str(dst))
        moved += 1
    
    print(f"成功移动 {moved} 个 ADR")
    if errors:
        print(f"错误 ({len(errors)}):")
        for e in errors:
            print(f"  {e}")
    
    # 输出结果
    print("\n=== 拆分结果 ===")
    for topic, subdir in sorted(TOPIC_TO_DIR.items(), key=lambda x: x[1]):
        d = ADR_DIR / subdir
        if d.exists():
            count = len(list(d.glob("*.md")))
            print(f"  {subdir}/ ({count} 个) — {topic}")

if __name__ == '__main__':
    main()

import { connectDshPage, until, autoDismissWelcome, bodyText } from '../non_deliverables_tools/dsh_parity/dumps/_e2e.mjs';
const { cdp, page } = await connectDshPage(9223);
await autoDismissWelcome(page);
await until('render', async () => (await bodyText(page)).length > 20, 20000);
const item = page.locator('[role=treeitem]').filter({ hasText: '未命名' }).first();
if (await item.count()) await item.click().catch(() => {});
await until('chat actions', async () => (await bodyText(page)).includes('好的回答'), 15000);
const composer = page.locator('textarea, [contenteditable=true]').first();
await composer.click();
await composer.fill('/feedback');
await page.waitForTimeout(600);
console.log('AFTER TYPE BODY', (await bodyText(page)).slice(-600));
await page.screenshot({ path: '.xxx/logs/feedback-slash.png' });
await composer.press('Enter');
await page.waitForTimeout(800);
console.log('DIALOGS', await page.locator('[role=dialog]').count());
console.log('BODY2', (await bodyText(page)).slice(-700));
await page.screenshot({ path: '.xxx/logs/feedback-slash2.png' });
await cdp.close();
